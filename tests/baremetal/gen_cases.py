#!/usr/bin/env python3
"""Emit cases.h: attn inputs plus the exact bytes Y must hold afterwards.

Expected bytes come from include/attn_core.h run on the host, and are also
checked here against the independent float64 model, so a bare-metal run that
matches them bit for bit is correct to within the model tolerance too.
"""

import struct
import sys
import tempfile
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "tools"))
import attn_host  # noqa: E402
import attn_model as am  # noqa: E402

CASES = [
    ("f32_1head", dict(n=4, e=8, h=1)),
    ("f32_4head_bias", dict(n=16, e=32, h=4)),
    ("f32_causal_mask", dict(n=11, e=16, h=4, mask=True, flags=am.F_CAUSAL)),
    ("f32_gqa", dict(n=10, e=32, h=8, h_kv=2, bias=False)),
    ("f32_scale", dict(n=6, e=8, h=2, scale=0.3)),
    ("bf16_bf16_causal", dict(n=16, e=32, h=4, in_dt=am.DT_BF16,
                              out_dt=am.DT_BF16, flags=am.F_CAUSAL)),
    ("bf16_f32_gpt2ish", dict(n=32, e=64, h=4, in_dt=am.DT_BF16,
                              flags=am.F_CAUSAL)),
]


def c_array(name, data, ctype, fmt):
    words = struct.unpack("<%d%s" % (len(data) // struct.calcsize(fmt), fmt),
                          data)
    body = ",".join(("0x%x" % w) for w in words)
    return ("static %s %s[%d] __attribute__((aligned(16))) = {%s};\n"
            % (ctype, name, len(words), body))


def blob(case, addr, nbytes):
    off = addr - case.image.base
    return bytes(case.image.buf[off:off + nbytes])


def emit_case(lib, name, kw):
    case = am.Case(np.random.default_rng(sum(map(ord, name))), **kw)
    rc, mem = attn_host.run(lib, case)
    assert rc == 0, name
    y = case.read_y(mem)
    exp = am.round_dtype(case.expected(), case.out_dt)
    assert np.allclose(y, exp, rtol=0, atol=case.tolerance()), name

    n, e = case.n, case.e
    kv = (case.h_kv or case.h) * (e // case.h)
    isz = 2 if case.in_dt == am.DT_BF16 else 4
    osz = 2 if case.out_dt == am.DT_BF16 else 4
    w = struct.unpack_from(am.WEIGHTS_FMT, case.image.buf,
                           case.w_addr - case.image.base)
    c = dict(zip(am.CFG_FIELDS, struct.unpack_from(
        am.CFG_FMT, case.image.buf, case.c_addr - case.image.base)))
    out = []
    p = name + "_"
    out.append(c_array(p + "x", blob(case, case.x_addr, n * e * isz),
                       "uint8_t", "B"))
    sizes = [e * e, e * kv, e * kv, e * e]
    names = ["wq", "wk", "wv", "wo"]
    for nm, addr, cnt in zip(names, w[:4], sizes):
        out.append(c_array(p + nm, blob(case, addr, cnt * isz), "uint8_t",
                           "B"))
    for nm, addr, cnt in zip(["bq", "bk", "bv", "bo"], w[4:], [e, kv, kv, e]):
        if addr:
            out.append(c_array(p + nm, blob(case, addr, cnt * 4), "uint8_t",
                               "B"))
    if c["mask"]:
        out.append(c_array(p + "mask", blob(case, c["mask"], n * n * 4),
                           "uint8_t", "B"))
    out.append(c_array(p + "expect", mem[case.y_addr - case.image.base:]
                       [:n * e * osz], "uint8_t", "B"))
    out.append("static uint8_t %sy[%d] __attribute__((aligned(16)));\n"
               % (p, n * e * osz))
    ptr = lambda nm, addr: "(uintptr_t) %s%s" % (p, nm) if addr else "0"
    out.append("static const struct attn_weights %sw = { %s };\n" % (p, ", ".join(
        ptr(nm, a) for nm, a in zip(names + ["bq", "bk", "bv", "bo"], w))))
    out.append("static const struct attn_cfg %scfg = { %d, %d, %d, %d, %d, %d, "
               "%d, 0x%x, 0, %s };\n" % (
                   p, c["n"], c["e"], c["h"], c["h_kv"], c["flags"],
                   c["in_dtype"], c["out_dtype"], c["scale_bits"],
                   ptr("mask", c["mask"])))
    entry = ('  { "%s", %sy, %sx, &%sw, &%scfg, %sexpect, sizeof %sy },\n'
             % (name, p, p, p, p, p, p))
    return "".join(out), entry


def main(out):
    with tempfile.TemporaryDirectory() as d:
        lib = attn_host.build(d)
        parts = [emit_case(lib, n, kw) for n, kw in CASES]
    with open(out, "w") as f:
        f.write("/* Generated by gen_cases.py; do not edit.  */\n\n")
        for body, _ in parts:
            f.write(body)
        f.write("\nstatic const struct attn_case cases[] = {\n")
        for _, entry in parts:
            f.write(entry)
        f.write("};\n")


if __name__ == "__main__":
    main(sys.argv[1])
