"""Scan the corpus for attention loops with the built toolchain.

The corpus under build/corpus is gitignored; one run of this tool is
committed as tests/corpus/scan.json and the table in docs/corpus.md is
generated from it.  Each file that compiles is built twice at -O2, once
with the recognizer and once with -fno-tree-loop-attn, and the objects are
compared: if they are identical the pass replaced nothing.  A file the
toolchain cannot compile is recorded with the first error instead of a
count, because a count would be a claim about code that was never built.

Run it inside the container that has out/toolchain mounted:

    python3 tools/corpus_scan.py --out tests/corpus/scan.json
"""

from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import re
import subprocess
import sys
import tempfile

REPO = pathlib.Path(__file__).resolve().parents[1]
CORPUS = REPO / "build" / "corpus"
GCC = REPO / "out" / "toolchain" / "bin" / "riscv64-unknown-elf-gcc"
OBJDUMP = REPO / "out" / "toolchain" / "bin" / "riscv64-unknown-elf-objdump"

# The bare-metal target has no POSIX clock and no mapping calls, and the
# version header is generated by CMake.  These stand-ins only let the front
# end reach the loops; nothing here is linked or run.
SHIM = "posix-clock.h"
SHIM_SYS = "sys/mman.h"
SHIM_VERSION = "ggml-version.h"

SHIMS = {
    SHIM: """\
#ifndef SHIM_POSIX_CLOCK_H
#define SHIM_POSIX_CLOCK_H
#include <time.h>
#ifndef CLOCK_REALTIME
#define CLOCK_REALTIME 0
#endif
#ifndef CLOCK_MONOTONIC
#define CLOCK_MONOTONIC 1
#endif
int clock_gettime (int, struct timespec *);
#endif
""",
    SHIM_SYS: """\
#ifndef SHIM_SYS_MMAN_H
#define SHIM_SYS_MMAN_H
#include <stddef.h>
#define PROT_READ 1
#define MAP_PRIVATE 2
#define MAP_FAILED ((void *) -1)
void *mmap (void *, size_t, int, int, int, long);
int munmap (void *, size_t);
#endif
""",
    SHIM_VERSION: """\
#pragma once
#define GGML_VERSION "shim"
#define GGML_COMMIT  "shim"
#define GGML_VERSION_MAJOR (1)
#define GGML_VERSION_MINOR (0)
#define GGML_VERSION_PATCH (0)
""",
}

# file, language, extra flags.  Paths are relative to the repository.
FILES: list[tuple[str, str, list[str]]] = [
    ("demo/mha_plain.c", "c", []),
    ("build/corpus/llama2c/run.c", "c", []),
    ("build/corpus/llama2c/runq.c", "c", []),
    ("build/corpus/llamacpp/ggml/src/ggml.c", "c", []),
    ("build/corpus/llamacpp/ggml/src/ggml-cpu/ggml-cpu.c", "c", ["-D_GNU_SOURCE"]),
    ("build/corpus/llamacpp/ggml/src/ggml-et/et-kernels/src/flash_attn_ext_f32.c", "c", []),
    ("build/corpus/llamacpp/ggml/src/ggml-et/et-kernels/src/flash_attn_ext_f16_me.c", "c", []),
    ("build/corpus/llamacpp/ggml/src/ggml-et/et-kernels/src/softmax_f32.c", "c", []),
    ("build/corpus/llamacpp/ggml/src/ggml-et/et-kernels/src/rope_f32.c", "c", []),
    ("build/corpus/llamacpp/ggml/src/ggml-et/et-kernels/src/gated_delta_net_f32.c", "c", []),
    ("build/corpus/llamacpp/ggml/src/ggml-et/et-kernels/src/rwkv_wkv6_f32.c", "c", []),
    ("build/corpus/llamacpp/ggml/src/ggml-hexagon/htp/flash-attn-ops.c", "c", []),
    ("build/corpus/llamacpp/ggml/src/ggml-hexagon/htp/softmax-ops.c", "c", []),
    ("build/corpus/mnn/source/backend/cpu/CPUAttention.cpp", "c++", []),
    ("build/corpus/mnn/source/backend/cpu/CPULinearAttention.cpp", "c++", []),
    ("build/corpus/mnn/source/backend/cpu/riscv/rvv/MNNRvvAttentionFunctions.cpp", "c++", []),
    ("build/corpus/ncnn/src/layer/multiheadattention.cpp", "c++", []),
    ("build/corpus/ncnn/src/layer/arm/multiheadattention_arm.cpp", "c++", []),
]

INCLUDES = [
    CORPUS / "llamacpp" / "ggml" / "include",
    CORPUS / "llamacpp" / "ggml" / "src",
    CORPUS / "llamacpp" / "ggml" / "src" / "ggml-cpu",
]

FLAGS = [
    "-march=rv64gc_xattn",
    "-mabi=lp64d",
    "-mcmodel=medany",
    "-O2",
    "-ffp-contract=off",
    "-w",
    "-fopt-info-loop-missed",
]

INSN = re.compile(r"^\s+[0-9a-f]+:\s", re.M)
ATTN = re.compile(r"^\s+[0-9a-f]+:\s+attn\s", re.M)
REASON = re.compile(r"attention loops not replaced: .*")


def shim_dir(root: pathlib.Path) -> pathlib.Path:
    for name, text in SHIMS.items():
        p = root / name
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="ascii")
    return root


def compile_one(src: pathlib.Path, lang: str, extra: list[str],
                out: pathlib.Path, shim: pathlib.Path, off: bool) -> tuple[
                    int, str]:
    cmd = [
        str(GCC), *FLAGS, *extra,
        "-include", str(shim / SHIM),
        *(f"-I{d}" for d in INCLUDES),
        "-I", str(shim),
        *(["-x", "c++"] if lang == "c++" else []),
        *(["-fno-tree-loop-attn"] if off else []),
        "-c", str(src), "-o", str(out),
    ]
    r = subprocess.run(cmd, capture_output=True, text=True)
    return r.returncode, r.stderr


def measure(obj: pathlib.Path) -> tuple[int, int, str]:
    if not obj.is_file():
        return 0, 0, ""
    dis = subprocess.run([str(OBJDUMP), "-d", "--no-show-raw-insn", str(obj)],
                         capture_output=True, text=True).stdout
    sha = hashlib.sha256(obj.read_bytes()).hexdigest()
    return len(INSN.findall(dis)), len(ATTN.findall(dis)), sha


def scan(tmp: pathlib.Path) -> tuple[list[dict[str, object]], str]:
    shim = shim_dir(tmp / "shim")
    rows: list[dict[str, object]] = []
    for rel, lang, extra in FILES:
        src = REPO / rel
        row: dict[str, object] = {"file": rel, "language": lang}
        if not src.is_file():
            row.update(status="absent", why="file is not in the corpus")
            rows.append(row)
            continue
        _, err = compile_one(src, lang, extra, tmp / "probe.o", shim, False)
        if "language c++ not recognized" in err:
            row.update(status="not built", attn=None,
                       why="this toolchain has no C++ front end "
                           "(--enable-languages=c)")
            rows.append(row)
            continue
        fatal = [ln for ln in err.splitlines() if "fatal error:" in ln]
        errors = [ln for ln in err.splitlines() if "error:" in ln]
        if not (tmp / "probe.o").is_file() or errors:
            first = (fatal or errors or err.splitlines() or [""])[-1]
            row.update(status="not built", attn=None,
                       why=first.strip().replace(str(REPO) + "/", "")[:200])
            rows.append(row)
            continue
        on = tmp / "on.o"
        off = tmp / "off.o"
        rcon, erron = compile_one(src, lang, extra, on, shim, False)
        rcoff, erroff = compile_one(src, lang, extra, off, shim, True)
        if rcon or rcoff:
            row.update(status="not built", attn=None,
                       why=(erron or erroff).strip().splitlines()[-1][:200])
            rows.append(row)
            continue
        ins_on, attn, sha_on = measure(on)
        ins_off, _, sha_off = measure(off)
        if attn:
            why = ["replaced with attn"]
        else:
            why = sorted(set(REASON.findall(erron))) or [
                "no candidate nest: the pass printed no rejection line"
            ]
        row.update(status="built", attn=attn, why="; ".join(why),
                   insns_on=ins_on, insns_off=ins_off,
                   same=sha_on == sha_off)
        rows.append(row)
    return rows, toolchain()


def toolchain() -> str:
    r = subprocess.run([str(GCC), "--version"], capture_output=True,
                       text=True)
    return r.stdout.splitlines()[0] if r.returncode == 0 else "unknown"


def table(rows: list[dict[str, object]]) -> str:
    head = ("| File | Built | `attn` | Instruction count, loops | "
            "Instruction count, recognizer |")
    lines = [head, "|---|---|---|---|---|"]
    for r in rows:
        built = "yes" if r["status"] == "built" else "no"
        attn = "-" if r["attn"] is None else str(r["attn"])
        on = "-" if r["status"] != "built" else str(r["insns_on"])
        off = "-" if r["status"] != "built" else str(r["insns_off"])
        lines.append(f"| `{r['file']}` | {built} | {attn} | {off} | {on} |")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=pathlib.Path,
                    default=REPO / "tests" / "corpus" / "scan.json")
    args = ap.parse_args(argv[1:])
    if not GCC.exists():
        print(f"no toolchain at {GCC}", file=sys.stderr)
        return 1
    with tempfile.TemporaryDirectory() as d:
        rows, tc = scan(pathlib.Path(d))
    doc = {"toolchain": tc, "rows": rows}
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(doc, indent=1) + "\n", encoding="ascii")
    print(table(rows))
    for r in rows:
        if r["status"] != "built":
            print(f"\n{r['file']}: {r['why']}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
